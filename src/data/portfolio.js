export function priorityFor({ hbuScore, irr, npv }) {
  if (npv > 0 && irr >= 0.12 && hbuScore >= 75) return 'High';
  if (npv > 0) return 'Medium';
  return 'Low';
}

/** Build a CAP record from a completed analysis session (FR-086, FR-087). */
export function recordFromSession(session, decision, nextId) {
  const { plot, results: r } = session;
  const rec = r.recommendation;
  const m = rec.metrics;
  const alt = r.financial.selectedAlternative;
  const status = decision?.status === 'accepted' ? 'Specialist endorsed — pending committee' : decision?.status === 'rejected' ? 'Not progressed' : 'Under assessment';
  const today = new Date();
  const next = new Date(today.getTime() + 30 * 864e5);
  return {
    id: nextId,
    plotNumber: plot.plotNumber,
    name: `${plot.community} — ${alt.use.shortName}`,
    community: plot.community,
    assetClass: alt.use.category,
    investmentType: alt.use.investmentType,
    recommendedUse: alt.use.name,
    structure: rec.structure.name.split(' (')[0],
    status,
    stage: decision?.status === 'rejected' ? 'Screening' : 'Feasibility',
    priority: priorityFor({ hbuScore: alt.total.value, irr: m.irr ?? 0, npv: m.npv }),
    indicativeValue: m.stabNoi / r.financial.inputs.exitCapRate,
    npv: m.npv,
    irr: m.irr,
    roi: m.roi,
    payback: m.payback,
    capex: m.totalCapex,
    hbuScore: alt.total.value,
    recommendation: `${rec.verdict.label} (AI recommendation; specialist decision: ${decision?.status ?? 'pending'})`,
    decisionNote: decision?.note ?? '',
    conditions: rec.conditions,
    riskFlags: rec.risks.length,
    userModified: r.financial.userModified,
    owner: 'Investment specialist (you)',
    nextReview: next.toISOString().slice(0, 10),
    updated: today.toISOString().slice(0, 10),
    source: `Captured from Investment Agentic AI session · plot ${plot.plotNumber}`,
    fromSession: true,
  };
}
