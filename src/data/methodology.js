// Catchment weighting: full weight within 1 km, tapering with distance.
export function catchmentWeight(distanceM, radiusM) {
  if (distanceM <= 1000) return 1;
  return Math.max(0.3, 1 - (distanceM - 1000) / (radiusM * 1.5));
}

